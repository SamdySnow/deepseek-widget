#!/bin/zsh
# 验证 click-through：把光标移到透明区域 / 角色本体上，观察窗口是否切换事件接收。
#
# 原理：窗口的 `ignoresMouseEvents` 状态会反映在 CGWindowList 的
# `kCGWindowLayer` 之外，无法直接读到，所以这里用「移动光标 + 尝试点击」的
# 间接方式不可行；改为直接问应用自己：通过 AXRaise 不行……
#
# 更可靠的做法：让挂件在切换状态时写一个标记文件。为避免侵入代码，
# 这里退化为【人工可核对的检查表】+ 自动化的「光标移开后是否还能收到事件」验证。
#
# 用法：Scripts/check_clickthrough.sh
set -u

echo "click-through 手工核对清单"
echo "================================"
cat <<'TXT'
请按顺序操作，确认每一项：

1) 把光标移到挂件左上角的空白处（气泡区之外的透明区域）
   → 点击左键：应在桌面上生效（选中桌面图标 / 切换 Finder 等），
     挂件不应有任何反应。

2) 把光标移到气泡上（如果气泡已展开）
   → 点击左键：同样应穿透到桌面，挂件不动。

3) 把光标移到小鲸鱼身上
   → 点击左键：应弹出/推进余额气泡，且伴随 Q 弹动画。
   → 按住拖动：挂件应跟随鼠标移动，松手后边缘吸附。

4) 光标悬停在小鲸鱼上
   → 右上角出现 ☰ 按钮；点击它应弹出菜单，且气泡不跟着切换。
   → 光标移开小鲸鱼后，☰ 按钮应消失。

5) 光标移到挂件透明区域
   → ☰ 按钮不应出现。

6) 锁定（菜单 → 锁定）
   → 把小鲸鱼拖到屏幕中间（便于观察），再从菜单勾上「锁定」。
   → 现象：鼠标移到小鲸鱼身上**不再**出现 ☰；点击不出气泡；按住拖不动；
     右键也不弹菜单；光标形状与桌面一致（窗口已完全让出鼠标）。
   → 点击小鲸鱼所在的屏幕位置：应在**下层应用**上生效（例如点到后面的
     浏览器 / 编辑器窗口），证明是真穿透而不只是「不响应」。
   → 解锁入口：菜单栏 🐋 → 「解锁挂件」（挂件本身已经点不动，这是唯一出路）。
   → 解锁后再点小鲸鱼，应恢复正常。

7) 锁定 + 托盘菜单的状态
   → 未锁定时，菜单栏 🐋 → 「解锁挂件」应为**置灰**不可点。
   → 锁定后同一项应变为可点。

8) 不透明度（菜单 → 不透明度滑块）
   → 拖动滑块：挂件应实时变淡 / 变浓。
   → 拉到最左（20%）：挂件明显变淡但仍可见（下限刻意不为 0，
     避免变成「挂件不见了」）。
   → 关键是**变淡不影响可点击性**：在 20% 时点小鲸鱼，仍应正常出气泡。

9) 重启后保持
   → 设置好锁定与不透明度后退出（菜单栏 🐋 → 退出）并重新启动。
   → 两项设置都应保留（写入 ~/.whale-widget-mac/config.json）。
   → 若旧版本升级上来：首次读取旧配置不应把缩放 / 位置重置
     （`--hitcheck` 有专门的回归断言覆盖这一点）。

10) 吸附（重点：吸附区比过去宽得多）
   → 把鲸鱼拖到**距屏幕左边约 100px** 处松手：应当被吸到最左边。
     （旧版这里不会吸附 —— 吸附区只有 24px，必须几乎顶到边缘。）
   → 距右边约 100px 松手：吸到最右边。
   → 距底边约 150px 松手：吸到底边。
   → 拖到**靠近顶部**松手：**不应**吸附（上边刻意不吸附，与网页版默认一致）。
   → 屏幕正中间松手：不应吸附（保持放下的位置）。
   → 吸附应当有约 0.16s 的顺滑滑动，而不是瞬移。

11) 翻转（重点：贴左必翻）
   → 把鲸鱼停到屏幕**左半边**（不必贴边）：小鲸鱼应左右翻转、朝向屏幕内侧，
     但**气泡里的文字与图片必须仍是正向、可读的**（只是朝向变，内容不跟着反）。
   → 同时确认：翻转前后**文字都稳稳落在泡泡正中间**，不会向左或向右偏。
     （曾经因为反翻挂在了 `.position` 之后，镜像后文字整体偏了约 15px；
     自动化已覆盖这一条：`--render` 会量「文字重心 vs 泡泡中心」）
     拖动过程中就应实时翻转，不必等松手。
   → 停到**右半边**：不翻转。
   → 贴左边吸附：**必翻**。
   → 贴右边吸附：不翻。
   → 菜单里关掉「贴左镜像翻转」后，即使停在左边也不翻。
   → 关掉「拖拽吸附屏幕边缘」后（此时不会吸附），把鲸鱼拖到**最左边**：
     仍然应当翻转（旧版这里永不翻转 —— 关吸附时朝向被置成了 none）。
   → 翻转后点小鲸鱼：**仍然点得动**（坐标映射要跟着镜像走）。

12) 重置位置
   → 把鲸鱼拖到屏幕中间后，菜单 → 「重置位置」：应回到右下角默认位。
   → 重置后朝向右（不翻转）。
   → 退出重开：仍在右下角默认位。

自动化的部分是「路由判定」本身（`--hitcheck` 覆盖了 zone 划分、面积占比、
锁定语义与不透明度的像素效果；`--e2e` 覆盖了真实窗口的 ignoresMouseEvents
切换、拖不动、**吸附到四边**、**窗口帧动画确实移动窗口**、**朝向翻转的四种情形**、
**镜像后的点击坐标映射**、**重置位置**），真实光标行为仍需真人确认 ——
因为 `ignoresMouseEvents` 的切换依赖全局鼠标监听，无法在无头环境下合成。
TXT
