#!/bin/zsh
# 验证 click-through：把光标移到透明区域 / 角色本体上，观察窗口是否切换事件接收。
#
# 原理：窗口的 `ignoresMouseEvents` 状态会反映在 CGWindowList 的
# `kCGWindowLayer` 之外，无法直接读到，所以这里用「移动光标 + 尝试点击」的
# 间接方式不可行；改为直接问应用自己：通过 AXRaise 不行……
#
# 更可靠的做法：让挂件在切换状态时写一个标记文件。为避免侵入代码，
# 这里退化为【人工可核对的检查表】+ 自动化的「光标移开后是否还能收到事件」验证。
#
# 用法：Scripts/check_clickthrough.sh
set -u

echo "click-through 手工核对清单"
echo "================================"
cat <<'TXT'
请按顺序操作，确认每一项：

1) 把光标移到挂件左上角的空白处（气泡区之外的透明区域）
   → 点击左键：应在桌面上生效（选中桌面图标 / 切换 Finder 等），
     挂件不应有任何反应。

2) 把光标移到气泡上（如果气泡已展开）
   → 点击左键：同样应穿透到桌面，挂件不动。

3) 把光标移到小鲸鱼身上
   → 点击左键：应弹出/推进余额气泡，且伴随 Q 弹动画。
   → 按住拖动：挂件应跟随鼠标移动，松手后边缘吸附。

4) 光标悬停在小鲸鱼上
   → 右上角出现 ☰ 按钮；点击它应弹出菜单，且气泡不跟着切换。
   → 光标移开小鲸鱼后，☰ 按钮应消失。

5) 光标移到挂件透明区域
   → ☰ 按钮不应出现。

自动化的部分是「路由判定」本身（`--hitcheck` 覆盖了 zone 划分与面积占比），
真实光标行为需要真人确认 —— 因为 `ignoresMouseEvents` 的切换依赖全局鼠标监听，
无法在无头环境下合成。
TXT
